def get_food_prompt_chunks(
    items: List[str] = FRIDGE_FOOD_ITEMS,
    chunk_size: int = 40,
) -> List[str]:
    """
    Split the list of food items into dot-separated prompt chunks for Grounding DINO.
    Keeps each prompt chunk safely within BERT's 512-token sequence limit.
    """
    chunks = []
    for i in range(0, len(items), chunk_size):
        chunk_items = items[i : i + chunk_size]
        chunks.append(" . ".join(chunk_items))
    return chunks
